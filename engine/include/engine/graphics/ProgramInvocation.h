// resolved handle to a location in a uniform buffer 
// tokens are templated in order to provide compile-time checks that your uniform types are correct
template<typename T>
struct UniformToken {
    // byte offset into uniform buffer
    uint64_t offset;

    // uniform buffer resource binding location
    std::pair<uint32_t, uint32_t> location;
};

// a ProgramInvocation is a container relating a Program and the resources required to run the program 
// to actually run a program, you need a ProgramInvocation
class ProgramInvocation {
public:
    void bind_uniform_buffer(
        std::string_view name,
        Buffer& uniform_buffer
    );
    void bind_sampled_texture(
        std::string_view name,
        Texture& texture,
        Sampler& sampler
    );

    // retrieve a token that can be used to set uniforms
    // meant to be done once at init-time as parsing the address string is slow
    template<typename T>
    UniformToken<T> get_uniform(std::string_view addr);

    // use generated tokens to set uniform values
    void set_uniform(UniformToken<int> token, int val);
    void set_uniform(UniformToken<float> token, float val);
    void set_uniform(UniformToken<glm::vec2> token, glm::vec2 val);
    void set_uniform(UniformToken<glm::vec3> token, glm::vec3 val);
    void set_uniform(UniformToken<glm::mat4> token, glm::mat4 val);

    // generate a token and set the uniform
    // convenience method for init time
    template<typename T>
    void set_uniform(std::string_view addr, T val) {
        set_uniform(get_uniform<T>(addr), val);
    }

protected:
    // a ResourceBinding describes the resource bound to some underlying slot
    struct ResourceBinding {
        ShaderResourceType type;
        struct UniformBuffer {
            Buffer* buffer = nullptr;
        } uniform_buffer;
        struct SampledTexture {
            Texture* texture = nullptr;
            Sampler* sampler = nullptr;
        } sampled_texture;

        static ResourceBinding create_uniform_buffer(Buffer& buffer) {
            ResourceBinding res;
            res.type = ShaderResourceType::UniformBuffer;
            res.uniform_buffer.buffer = &buffer;
            return res;
        }
        static ResourceBinding create_sampled_texture(Texture& texture, Sampler& sampler) {
            ResourceBinding res;
            res.type = ShaderResourceType::SampledTexture;
            res.sampled_texture.texture = &texture;
            res.sampled_texture.sampler = &sampler;
            return res;
        }
    };

    ProgramInvocation(
        GraphicsDevice& device,
        Program& program
    );
    virtual ~ProgramInvocation() = 0;

    // if the underlying slot refers to a uniform buffer, returns the buffer
    // otherwise throws an error
    Buffer& get_uniform_buffer(ShaderResourceLocation location);

    // bind a resource to this program invocation
    // marks the location as dirty
    void bind_resource(ShaderResourceLocation location, ResourceBinding resource);

    // internal api to get some already bound resource binding
    ResourceBinding& get_resource(ShaderResourceLocation location);

    // no-op if all resource slots have a resource bound to them
    // throws errors if otherwise
    void validate_resource_bindings();

    // underlying graphics API
    GraphicsDevice& device;

    // underlying program
    Program& program;

    // uniform buffers automatically generated by the invocation
    std::vector<std::unique_ptr<Buffer>> uniform_buffers;

    // map slot -> resource binding
    std::map<ShaderResourceLocation, ResourceBinding> bound_resources;

    // set of dirty slots, these are set when a resource gets bound/unbound from a slot
    // these are mainly so that the underlying driver implementations know when some resource changed
    // the underlying driver can do whatever it wants with these
    std::set<ShaderResourceLocation> dirty_resources;
};


// how to assign each element in a bound vertex buffer
enum class VertexInputRate {
    Vertex,		// every element goes to a different vertex
    Instance,	// every element goes to a different instance
};

// how each vertex attribute element should be interpreted
// depending on how each attribute is formatted, they may take up multiple locations
enum class VertexFormat {
    Float32x1,
    Float32x2,
    Float32x3,
    Float32x4,
    Float32x4x4,
};

// how each index element should be interpreted
enum class IndexFormat {
    UInt16,
    UInt32,
};

// everything required to invoke a rendering program
class RenderingProgramInvocation : public ProgramInvocation {
public: 
    void bind_vertex_attribute(
        std::string_view name,
        Buffer& buffer,
        uint32_t offset,
        uint32_t stride,
        VertexInputRate rate,
        VertexFormat format
    );
    void bind_index_buffer(
        Buffer& buffer,
        IndexFormat format
    );
    void bind_render_target(
        RenderTarget& target
    );

    // modifies the behaviour when executing the program
    void do_depth_testing(bool val);
    void do_clear_color(bool val);
    void do_clear_depth(bool val);

    void do_clipping(bool val);
    void set_clip_rect(
        int32_t min_x,
        int32_t min_y,
        uint32_t width,
        uint32_t height
    );

    // validates that everything is bound before drawing
	void draw(
        uint32_t nr_primitives, 
        uint32_t nr_instances = 1,
        uint32_t first_primitive = 0,
        uint32_t first_instance = 0
    );

protected:
    RenderingProgramInvocation(
        GraphicsDevice& device,
        Program& program
    );

	virtual void draw_impl(
        uint32_t nr_primitives, 
        uint32_t nr_instances,
        uint32_t first_primitive,
        uint32_t first_instance
    ) = 0;

    // describes a contiguous region of vertex attribute locations
    // describes how to interpret the data in a buffer / how that data should be fed into the shader
    struct VertexAttribute { 
        // derived from shader vertex input layout
        uint32_t location;          // first location
        uint32_t nr_locations;      // number of locations this attribute spans

        // bound by the user
        Buffer* buffer = nullptr;   // null = unbound
        uint32_t offset;            // byte of the first element
        uint32_t stride;            // bytes between elements
        VertexInputRate rate;       // the granularity that an element in the buffer should be interpreted at
        VertexFormat format;        // how the underlying driver should interpret the data in the buffer
    };

    // mapping vertex attribute first location -> vertex attribute
    std::map<uint32_t, VertexAttribute> attributes;

    // set of vertex attributes that have a buffer bound to them
    std::set<uint32_t> bound_attributes;

    // set of dirty vertex attributes, these are set when the user binds/unbinds a buffer from a vertex attribute
    // these are mainly so that the underlying driver implementations know when a vertex attribute changed
    // the underlying implementation is free to do whatever it wants with this
    std::set<uint32_t> dirty_attributes;

	// optionally bind an index buffer for indexed rendering
	struct IndexBufferBinding {
		Buffer* buffer;
		IndexFormat format;
	};
	std::optional<IndexBufferBinding> index_buffer;

    // set when the user binds/unbinds the index buffer
    bool dirty_index_buffer = false;

    // target this invocation will render to
    // render target should be validated before being bound
    std::optional<RenderTarget*> render_target;

    // set when the user binds/unbinds the render target
    bool dirty_render_target = false;

    // if not set, defaults to true if a depth buffer is bound to the render target false otherwise
    // it is an error to set this to true when the render target does not have a depth buffer
    std::optional<bool> depth_testing = std::nullopt;

    // clear flags sent to the render target at the beginning of execution
    ClearFlags clear_flags = ClearFlags::Color | ClearFlags::Depth;

    // clip rect limits the area that gets rendered to on the target
    // by default, the clip rect contains the entire target
    int32_t clip_min_x, clip_min_y;
    uint32_t clip_width, clip_height;
    bool clipping = false;
};

